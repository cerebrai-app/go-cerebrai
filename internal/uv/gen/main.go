// Command gen writes release.go in the current directory: the uv version
// brainctl installs and the SHA-256 of that release's archive for each
// platform brainctl supports, from the release's sha256.sum. Run it through
// go generate in internal/uv after changing the version on the go:generate
// line in uv.go.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
)

// triples are the platforms brainctl supports; hostTriple in platform.go
// returns one of them.
var triples = []string{
	"aarch64-apple-darwin",
	"aarch64-pc-windows-msvc",
	"aarch64-unknown-linux-gnu",
	"aarch64-unknown-linux-musl",
	"x86_64-apple-darwin",
	"x86_64-pc-windows-msvc",
	"x86_64-unknown-linux-gnu",
	"x86_64-unknown-linux-musl",
}

var (
	versionPattern = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)
	hashPattern    = regexp.MustCompile(`^[0-9a-f]{64}$`)
)

func main() {
	version := flag.String("version", "", "uv release, e.g. 0.13.9")
	flag.Parse()
	if !versionPattern.MatchString(*version) {
		log.Fatalf("-version %q: want a uv release such as 0.13.9", *version)
	}
	url := "https://github.com/astral-sh/uv/releases/download/" + *version + "/sha256.sum"
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		log.Fatalf("GET %s: %v", url, err)
	}

	// Lines are "<sha256> *<file>" or "<sha256>  <file>".
	sums := map[string]string{}
	for line := range strings.Lines(string(body)) {
		fields := strings.Fields(line)
		if len(fields) == 2 && hashPattern.MatchString(fields[0]) {
			sums[strings.TrimPrefix(fields[1], "*")] = fields[0]
		}
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by go run ./gen -version %s; DO NOT EDIT.\n\n", *version)
	out.WriteString("package uv\n\n")
	out.WriteString("// Version is the uv release brainctl installs.\n")
	fmt.Fprintf(&out, "const Version = %q\n\n", *version)
	out.WriteString("// archiveSHA256 is the SHA-256 of Version's archive for each platform.\n")
	out.WriteString("var archiveSHA256 = map[string]string{\n")
	for _, triple := range slices.Sorted(slices.Values(triples)) {
		name := archiveName(triple)
		sum, ok := sums[name]
		if !ok {
			log.Fatalf("%s has no checksum for %s", url, name)
		}
		fmt.Fprintf(&out, "\t%q: %q,\n", triple, sum)
	}
	out.WriteString("}\n")
	src, err := format.Source([]byte(out.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("release.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// archiveName must match archiveName in install.go.
func archiveName(triple string) string {
	if strings.HasSuffix(triple, "-windows-msvc") {
		return "uv-" + triple + ".zip"
	}
	return "uv-" + triple + ".tar.gz"
}
